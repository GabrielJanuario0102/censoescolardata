
import psycopg2
from psycopg2.extras import execute_values
from pathlib import Path

import pandas as pd


BASE_DIR = Path(__file__).resolve().parent

ARQUIVO_CSV = BASE_DIR / "Tabela_Matricula_2025_V2.csv"

# Paginação
TAMANHO_PAGINA = 10000

DB_HOST = "localhost"
DB_NAME = "censoescolar"
DB_USER = "postgres"
DB_PASSWORD = "123456"
DB_PORT = "5435"
ESTADOS = [
    "AL", "BA", "CE", "MA", "PB",
    "PE", "PI", "RN", "SE",
    "ES", "MG", "RJ", "SP",
]

MAPEAMENTO = {
    "NO_ENTIDADE": "no_entidade",
    "CO_ENTIDADE": "co_entidade",
    "NO_UF": "no_uf",
    "SG_UF": "sg_uf",
    "CO_UF": "co_uf",
    "NO_MUNICIPIO": "no_municipio",
    "CO_MUNICIPIO": "co_municipio",
    "NU_ANO_CENSO": "nu_ano_censo",
    "NO_REGIAO": "no_regiao",
    "CO_REGIAO": "co_regiao",
    "QT_MAT_BAS": "qt_mat_bas",
    "QT_MAT_INF": "qt_mat_inf",
    "QT_MAT_FUND": "qt_mat_fund",
    "QT_MAT_MED": "qt_mat_med",
    "QT_MAT_PROF": "qt_mat_prof",
    "QT_MAT_EJA": "qt_mat_eja",
    "QT_MAT_ESP": "qt_mat_esp",
}

COLUNAS_CSV = list(MAPEAMENTO.keys())
COLUNAS_BANCO = list(MAPEAMENTO.values())


SQL_CRIAR_TABELA = """
CREATE TABLE IF NOT EXISTS tb_instituicao_ensino (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    no_entidade TEXT NOT NULL,
    co_entidade BIGINT NOT NULL UNIQUE,

    no_uf TEXT NOT NULL,
    sg_uf TEXT NOT NULL,
    co_uf BIGINT NOT NULL,

    no_municipio TEXT NOT NULL,
    co_municipio BIGINT NOT NULL,

    no_mesorregiao TEXT DEFAULT NULL,
    co_mesorregiao BIGINT DEFAULT NULL,

    no_microrregiao TEXT DEFAULT NULL,
    co_microrregiao BIGINT DEFAULT NULL,

    nu_ano_censo INTEGER NOT NULL,

    no_regiao TEXT,
    co_regiao BIGINT,

    qt_mat_bas BIGINT DEFAULT 0,
    qt_mat_inf BIGINT DEFAULT 0,
    qt_mat_fund BIGINT DEFAULT 0,
    qt_mat_med BIGINT DEFAULT 0,
    qt_mat_prof BIGINT DEFAULT 0,
    qt_mat_eja BIGINT DEFAULT 0,
    qt_mat_esp BIGINT DEFAULT 0,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP
);
"""


SQL_INSERIR = f"""
INSERT INTO tb_instituicao_ensino (
    {", ".join(COLUNAS_BANCO)}
)
VALUES %s
ON CONFLICT (co_entidade) DO UPDATE SET
    {", ".join(
        f"{coluna} = EXCLUDED.{coluna}"
        for coluna in COLUNAS_BANCO
        if coluna != "co_entidade"
    )};
"""


def get_db_connection():

    return psycopg2.connect(
        host=DB_HOST,
        database=DB_NAME,
        user=DB_USER,
        password=DB_PASSWORD,
        port=DB_PORT
    )


def importar_csv():

    if not ARQUIVO_CSV.exists():
        raise FileNotFoundError(
            f"Arquivo CSV não encontrado: {ARQUIVO_CSV}"
        )

    total_lido = 0
    total_filtrado = 0

    conexao = get_db_connection()

    try:
        with conexao.cursor() as cursor:

            cursor.execute(SQL_CRIAR_TABELA)

        conexao.commit()

        leitor = pd.read_csv(
            ARQUIVO_CSV,
            sep=";",
            usecols=COLUNAS_CSV,
            chunksize=TAMANHO_PAGINA,
            encoding="latin1",
            low_memory=False,
        )

        for numero_pagina, pagina in enumerate(leitor, start=1):

            total_lido += len(pagina)

            ano = pd.to_numeric(
                pagina["NU_ANO_CENSO"],
                errors="coerce",
            )

            pagina["SG_UF"] = (
                pagina["SG_UF"]
                .astype("string")
                .str.strip()
                .str.upper()
            )

            pagina = pagina[
                (ano == 2025)
                & pagina["SG_UF"].isin(ESTADOS)
            ].copy()

            if pagina.empty:
                print(
                    f"Página {numero_pagina}: "
                    "nenhum registro elegível."
                )
                continue

            # Renomeia as colunas
            pagina = pagina.rename(columns=MAPEAMENTO)

            # Converte campos textuais
            for coluna in [
                "no_entidade",
                "no_uf",
                "sg_uf",
                "no_municipio",
                "no_regiao",
            ]:
                pagina[coluna] = pagina[coluna].astype("string")

            # Converte campos numéricos
            colunas_numericas = [
                "co_entidade",
                "co_uf",
                "co_municipio",
                "nu_ano_censo",
                "co_regiao",
                "qt_mat_bas",
                "qt_mat_inf",
                "qt_mat_fund",
                "qt_mat_med",
                "qt_mat_prof",
                "qt_mat_eja",
                "qt_mat_esp",
            ]

            for coluna in colunas_numericas:
                pagina[coluna] = pd.to_numeric(
                    pagina[coluna],
                    errors="coerce",
                ).astype("Int64")

            # Seleciona as colunas na ordem correta
            pagina = pagina[COLUNAS_BANCO]

            # Substitui valores ausentes por None (SQL NULL)
            pagina = pagina.astype(object).where(
                pagina.notna(), None
            )

            registros = list(
                pagina.itertuples(index=False, name=None)
            )

            try:
                with conexao.cursor() as cursor:

                    execute_values(
                        cursor,
                        SQL_INSERIR,
                        registros,
                        page_size=TAMANHO_PAGINA
                    )

                conexao.commit()

            except Exception:
                conexao.rollback()
                raise

            total_filtrado += len(registros)

            print(
                f"Página {numero_pagina}: "
                f"{len(registros)} registros processados."
            )

    finally:
        conexao.close()

    print("\nImportação concluída!")
    print(f"Linhas lidas: {total_lido}")
    print(f"Linhas filtradas e processadas: {total_filtrado}")
    print(f"Banco de dados: {DB_NAME}")


if __name__ == "__main__":
    importar_csv()
